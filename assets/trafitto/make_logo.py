"""
Trafitto Launcher logo: a T inside a hexagon, split down the middle and pierced ("trafitto")
by a red slash. Generates the adaptive icon foreground + monochrome vectors and an SVG.

All shapes are plain convex polygons (no clip paths), so the output renders the same everywhere.
Run: python3 assets/trafitto/make_logo.py
"""
import math
import os

ROOT = os.path.join(os.path.dirname(__file__), "..", "..")
C = 54.0                  # center of the 108x108 adaptive icon canvas (safe zone: radius 33)
R_OUT = 27.0              # hexagon circumradius
STROKE = 3.2              # hexagon ring thickness
INSET = 2.4               # gap between ring and T
SPLIT = 1.6               # vertical split through the T
BAR = (38.5, 43.5)        # T bar, top and bottom
STEM = 5.4                # half width of the T stem
CUT_POINT = (54.0, 55.6)  # the slash passes here...
CUT_DIR = (2.0, -1.0)     # ...going up-right, 1 in 2
CUT_GAP = 3.0             # gap the slash opens in the white shapes
SHIFT = 0.7               # the upper half slides along the cut
BLADE = (30.0, 30.0, 2.8) # length towards lower-left, towards upper-right, max thickness

WHITE, RED, BG = "#F2F2F2", "#E10600", "#0F1012"


def hexagon(r):
    return [(C + r * math.cos(math.radians(a)), C + r * math.sin(math.radians(a)))
            for a in (-90, -30, 30, 90, 150, 210)]


def clip(poly, a, b, c):
    """Keep the part of a convex polygon where a*x + b*y + c >= 0 (Sutherland-Hodgman)."""
    if poly is None:
        return None
    out = []
    for i, p in enumerate(poly):
        q = poly[(i + 1) % len(poly)]
        fp, fq = a * p[0] + b * p[1] + c, a * q[0] + b * q[1] + c
        if fp >= 0:
            out.append(p)
        if (fp >= 0) != (fq >= 0):
            t = fp / (fp - fq)
            out.append((p[0] + t * (q[0] - p[0]), p[1] + t * (q[1] - p[1])))
    return out if len(out) >= 3 else None


def white_shapes():
    outer, inner = hexagon(R_OUT), hexagon(R_OUT - STROKE / math.cos(math.radians(30)))
    ring = [[outer[i], outer[(i + 1) % 6], inner[(i + 1) % 6], inner[i]] for i in range(6)]
    # The T is the inset hexagon cut to a T: its ends run parallel to the ring
    inset = hexagon(R_OUT - (STROKE + INSET) / math.cos(math.radians(30)))
    bar = clip(clip(inset, 0, 1, -BAR[0]), 0, -1, BAR[1])
    stem = clip(clip(clip(inset, 1, 0, -(C - STEM)), -1, 0, C + STEM), 0, 1, -(BAR[1] - 0.5))
    shapes = []
    for poly in ring + [bar, stem]:
        # Vertical split from the top of the T down through the bottom of the ring
        shapes.append(clip(poly, -1, 0, C - SPLIT / 2))
        shapes.append(clip(poly, 1, 0, -(C + SPLIT / 2)))
        middle = clip(clip(poly, 1, 0, -(C - SPLIT / 2)), -1, 0, C + SPLIT / 2)
        shapes.append(clip(middle, 0, -1, BAR[0]))
    return [s for s in shapes if s]


def sliced():
    """White shapes cut along the slash, the upper half slid a bit along it."""
    dx, dy = CUT_DIR
    length = math.hypot(dx, dy)
    nx, ny = -dy / length, dx / length  # normal pointing to the lower-right side
    px, py = CUT_POINT
    c = -(nx * px + ny * py)
    sx, sy = dx / length * SHIFT, dy / length * SHIFT
    pieces = []
    for poly in white_shapes():
        lower = clip(poly, nx, ny, c - CUT_GAP / 2)
        upper = clip(poly, -nx, -ny, -c - CUT_GAP / 2)
        if lower:
            pieces.append(lower)
        if upper:
            pieces.append([(x + sx, y + sy) for x, y in upper])
    return pieces


def blade_path():
    dx, dy = CUT_DIR
    length = math.hypot(dx, dy)
    ux, uy = dx / length, dy / length
    nx, ny = -uy, ux
    px, py = CUT_POINT
    back, front, thick = BLADE
    a = (px - ux * back, py - uy * back)
    b = (px + ux * front, py + uy * front)
    # Widest a bit towards the upper-right, sharp at both ends
    m = (px + ux * front * 0.2, py + uy * front * 0.2)
    k1 = (m[0] + nx * thick, m[1] + ny * thick)
    k2 = (m[0] - nx * thick, m[1] - ny * thick)
    f = lambda p: f"{p[0]:.2f},{p[1]:.2f}"
    return f"M{f(a)} Q{f(k1)} {f(b)} Q{f(k2)} {f(a)} Z"


def polys_path(polys):
    return " ".join("M" + " L".join(f"{x:.2f},{y:.2f}" for x, y in p) + " Z" for p in polys)


def vector(white, red):
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by assets/trafitto/make_logo.py, edit that instead -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path
        android:fillColor="{white}"
        android:pathData="{polys_path(sliced())}" />
    <path
        android:fillColor="{red}"
        android:pathData="{blade_path()}" />
</vector>
"""


def svg(size, background):
    bg = f'<rect width="108" height="108" rx="24" fill="{BG}"/>' if background else ""
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 108 108">
{bg}<path fill="{WHITE}" d="{polys_path(sliced())}"/>
<path fill="{RED}" d="{blade_path()}"/>
</svg>
"""


def write(path, text):
    with open(os.path.join(ROOT, path), "w") as f:
        f.write(text)


if __name__ == "__main__":
    write("core/base/src/main/res/drawable/ic_launcher_foreground.xml", vector(WHITE, RED))
    write("core/base/src/main/res/drawable/ic_launcher_monochrome.xml", vector("#FFFFFF", "#FFFFFF"))
    write("assets/trafitto/logo.svg", svg(512, background=True))
